import esbuild from 'esbuild';
import process from 'process';
import fs from 'node:fs';
import path from 'node:path';
import { builtinModules } from 'node:module';
import { rawEsbuildPlugin, scopedEsbuildPlugin } from './scripts/scoped.mjs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// Every build is also COPIED into the dev vault's plugin folder (copies, not
// symlinks, so the vault works on a machine that never builds). The vault is
// $HEXLORE_VAULT, else ../obsidian-test-vault; "none" turns this off.
const vaultSetting = process.env.HEXLORE_VAULT ?? '../obsidian-test-vault';
const vault = vaultSetting === 'none' ? null : path.resolve(vaultSetting);
const OUTPUTS = ['main.js', 'manifest.json', 'styles.css'];

function installIntoVault() {
	if (vault === null || !fs.existsSync(path.join(vault, '.obsidian'))) return;
	const dir = path.join(vault, '.obsidian', 'plugins', 'hexlore');
	fs.mkdirSync(dir, { recursive: true });
	for (const f of OUTPUTS) {
		const to = path.join(dir, f);
		// An older setup symlinked these; replace the link, not its target.
		if (fs.lstatSync(to, { throwIfNoEntry: false })?.isSymbolicLink()) fs.unlinkSync(to);
		fs.copyFileSync(f, to);
	}
	// The "Hot Reload" community plugin reloads folders holding this marker.
	fs.writeFileSync(path.join(dir, '.hotreload'), '');
	console.log(`installed into ${path.relative(process.cwd(), dir)}`);
}

const installPlugin = {
	name: 'install-into-vault',
	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length === 0) installIntoVault();
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	plugins: [scopedEsbuildPlugin, rawEsbuildPlugin, installPlugin],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
	// styles.css is not part of the bundle, so esbuild does not watch it.
	fs.watch('styles.css', () => installIntoVault());
}
